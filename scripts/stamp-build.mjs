// Writes src/buildInfo.js from package.json version, a git sha, and America/Los_Angeles builtAt.
// Sha source: STAMP_GIT_SHA || GITHUB_SHA (sliced to 7) || `git rev-parse --short HEAD`.
//
// Local PRs: commit the feature first, then `npm run stamp` and commit only src/buildInfo.js
// as the LAST commit (`chore: stamp`). Never stamp before the feature commit — that records
// the parent. That local tip lags one sha until Pages deploys with GITHUB_SHA.
//
// docs/ci/pages-stamp.yml stamps GITHUB_SHA on push to main and uploads that tree
// (install it at .github/workflows/pages-stamp.yml). It does not commit the stamp back.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pkgPath = join(root, 'package.json');
const pkg = JSON.parse(readFileSync(pkgPath, 'utf8'));

if (!pkg.version) {
    pkg.version = '0.1.0';
    writeFileSync(pkgPath, JSON.stringify(pkg, null, 2) + '\n');
}

const version = String(pkg.version);

function shaFromEnv() {
    const raw = String(process.env.STAMP_GIT_SHA || process.env.GITHUB_SHA || '').trim();
    if (!raw) return '';
    return raw.slice(0, 7);
}

let gitSha = shaFromEnv();
if (!gitSha) {
    try {
        gitSha = execFileSync('git', ['rev-parse', '--short', 'HEAD'], {
            cwd: root,
            encoding: 'utf8',
        }).trim();
    } catch {
        gitSha = 'unknown';
    }
}

const builtAt = isoInZone(new Date(), 'America/Los_Angeles');
const banner = `// Generated by scripts/stamp-build.mjs. Do not edit by hand.
// Local: npm run stamp as the last commit (chore: stamp). Never stamp before the feature.
`;
const body = `${banner}export const version = ${JSON.stringify(version)};
export const gitSha = ${JSON.stringify(gitSha)};
export const builtAt = ${JSON.stringify(builtAt)};
`;

writeFileSync(join(root, 'src', 'buildInfo.js'), body);
console.log(`stamped v${version} ${gitSha} ${builtAt}`);

/** ISO-8601 local time in `timeZone`, with a numeric offset or Z. */
function isoInZone(date, timeZone) {
    const dtf = new Intl.DateTimeFormat('en-US', {
        timeZone,
        year: 'numeric',
        month: '2-digit',
        day: '2-digit',
        hour: '2-digit',
        minute: '2-digit',
        second: '2-digit',
        hourCycle: 'h23',
        timeZoneName: 'longOffset',
    });
    const parts = {};
    for (const part of dtf.formatToParts(date)) {
        if (part.type !== 'literal') parts[part.type] = part.value;
    }
    const hour = parts.hour === '24' ? '00' : parts.hour;
    let offset = String(parts.timeZoneName || 'GMT').replace(/^GMT|^UTC/, '');
    if (offset === '' || offset === '+00:00' || offset === '+0') {
        return `${parts.year}-${parts.month}-${parts.day}T${hour}:${parts.minute}:${parts.second}Z`;
    }
    const match = offset.match(/^([+-])(\d{1,2})(?::?(\d{2}))?$/);
    if (match) offset = `${match[1]}${match[2].padStart(2, '0')}:${match[3] || '00'}`;
    return `${parts.year}-${parts.month}-${parts.day}T${hour}:${parts.minute}:${parts.second}${offset}`;
}
